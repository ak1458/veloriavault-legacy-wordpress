/**
 * Generates inc/icons-data.php from lucide-react so icons are byte-identical
 * to the headless storefront.
 *   node tools/build-icons.mjs <path-to-node_modules/lucide-react>
 *   npm run icons -- <path-to-node_modules/lucide-react>
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const lucide = process.argv[2];
if (!lucide) {
  throw new Error("Usage: npm run icons -- <path-to-node_modules/lucide-react>. No archived source is read automatically.");
}
const NAMES = ["Menu","X","ShoppingBag","Heart","User","ChevronDown","Package","Instagram","Facebook","ArrowUp","Loader2","CheckCircle","ShoppingCart","ChevronLeft","ChevronRight","RefreshCw","ShieldCheck","Truck","Star","Search","Check","ChevronUp","Copy","LayoutGrid","Maximize2","Minus","Plus","Tag","Sparkles","Camera","ImagePlus","Trash2","Shield","ArrowLeft","CreditCard","ArrowRight","AlertCircle","Mail","Phone","Send","Eye","EyeOff","FileText","HelpCircle","LogOut","CheckCircle2","MapPin","XCircle","MessageCircle"];

const index = readFileSync(join(lucide, "dist/esm/lucide-react.js"), "utf8");
const files = {};
for (const line of index.split("\n")) {
  const m = line.match(/^export \{([^}]*)\} from '(\.\/icons\/[^']+)'/);
  if (!m) continue;
  for (const part of m[1].split(",")) {
    const alias = part.trim().match(/as (\w+)$/);
    if (alias) files[alias[1]] = m[2];
  }
}

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;");
const out = {};
for (const name of NAMES) {
  if (!files[name]) throw new Error("No lucide icon " + name);
  const mod = await import(pathToFileURL(join(lucide, "dist/esm", files[name])).href);
  out[name] = mod.__iconNode.map(([tag, attrs]) =>
    "<" + tag + Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => ` ${k}="${esc(v)}"`).join("") + "/>"
  ).join("");
}

const kebab = (n) => n.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Za-z])(\d)/g, "$1-$2").toLowerCase();
let php = "<?php\n/**\n * Generated by tools/build-icons.mjs from lucide-react 0.577.0 (ISC). Do not edit.\n *\n * @package Veloria\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn array(\n";
for (const [name, svg] of Object.entries(out)) {
  const quoted = svg.split("\\").join("\\\\").split("'").join("\\'");
  php += `\t'${kebab(name)}' => '${quoted}',\n`;
}
php += ");\n";
writeFileSync(join(here, "../inc/icons-data.php"), php);
console.log(Object.keys(out).length + " icons written");
